/// Historical leftover from the pre-#1696 V8/`deno_core` fallback runtime
/// (`perry-jsruntime`, removed). `ctx.js_modules` is only ever populated
/// alongside `ctx.js_runtime_importers` (see `collect_modules.rs`), and
/// `enforce_js_runtime_gate` (`bootstrap.rs`) hard-errors the build as soon
/// as `js_runtime_importers` is non-empty — well before this function's
/// caller runs. In current builds `ctx.js_modules` is therefore always
/// empty here, so this function is effectively dead code kept around
/// for the (currently unreachable) day a JS engine ships again.
pub(super) fn generate_js_bundle(ctx: &CompilationContext, output_dir: &Path) -> Result<PathBuf> {
    let bundle_path = output_dir.join("__perry_js_bundle.js");

    let mut bundle = String::new();
    bundle.push_str("// Auto-generated JS bundle by Perry\n");
    bundle.push_str("// This file contains all JavaScript modules needed at runtime\n\n");

    bundle.push_str("globalThis.__COMPILETS_MODULES = {};\n\n");

    for (specifier, module) in &ctx.js_modules {
        // Escape the source code for embedding
        let escaped_source = module
            .source
            .replace('\\', "\\\\")
            .replace('`', "\\`")
            .replace("${", "\\${");

        bundle.push_str(&format!(
            "globalThis.__COMPILETS_MODULES[{:?}] = `{}`;\n",
            specifier, escaped_source
        ));
    }

    fs::write(&bundle_path, &bundle)?;
    Ok(bundle_path)
}

/// Issue #818 follow-up, now historical: this generated a C constructor
/// that registered every bundled JS module (and bare-specifier alias)
/// into `perry-jsruntime`'s embedded-module map at startup, so the V8
/// fallback `ModuleLoader` could consult the in-memory map before
/// touching disk. `perry-jsruntime` (V8 via `deno_core`) was removed in
/// #1696 — Perry ships no JS engine and compiles TypeScript ahead-of-time
/// only, so `js_register_embedded_module`/`js_register_embedded_alias`
/// (declared as `extern` below) no longer have any implementation to
/// link against.
///
/// Like `generate_js_bundle` above, this function is effectively dead
/// code today: `ctx.js_modules` can't be non-empty by the time its
/// caller runs, because `enforce_js_runtime_gate` hard-errors the build
/// as soon as any entry lands in `ctx.js_modules` (see that function's
/// doc comment). Kept for reference / in case a JS engine returns.
pub(super) fn generate_embedded_js_object(
    ctx: &CompilationContext,
    output_dir: &Path,
) -> Result<PathBuf> {
    let c_path = output_dir.join("__perry_embedded_js.c");
    let obj_path = output_dir.join("__perry_embedded_js.o");

    let mut c = String::new();
    c.push_str("// Auto-generated by Perry — embedded JS module map\n");
    c.push_str("// Constructor populates the V8 fallback ModuleLoader's in-memory\n");
    c.push_str("// cache so the resulting binary needs no node_modules/ at runtime.\n");
    c.push_str("#include <stddef.h>\n\n");
    c.push_str("extern void js_register_embedded_module(const char *path, size_t path_len, const char *source, size_t source_len);\n");
    c.push_str("extern void js_register_embedded_alias(const char *specifier, size_t specifier_len, const char *path, size_t path_len);\n\n");

    // Emit per-module string literals + a length pair.
    for (idx, (specifier, module)) in ctx.js_modules.iter().enumerate() {
        let path_lit = c_string_literal(specifier);
        let src_lit = c_string_literal(&module.source);
        c.push_str(&format!(
            "static const char PERRY_EMB_PATH_{idx}[] = {path_lit};\n"
        ));
        c.push_str(&format!(
            "static const size_t PERRY_EMB_PATH_LEN_{idx} = {};\n",
            specifier.len()
        ));
        c.push_str(&format!(
            "static const char PERRY_EMB_SRC_{idx}[] = {src_lit};\n"
        ));
        c.push_str(&format!(
            "static const size_t PERRY_EMB_SRC_LEN_{idx} = {};\n",
            module.source.len()
        ));
    }

    // Bare-specifier aliases: walk every native + JS module's resolved imports
    // and pick the (source_specifier, resolved_path) pairs whose
    // `resolved_path` is in `js_modules`. That captures both top-level
    // bare imports like `import { Hono } from "hono"` and JS→JS bare
    // imports (e.g. one V8-fallback module importing another package).
    let mut aliases: std::collections::BTreeMap<String, String> = std::collections::BTreeMap::new();
    for hir_module in ctx.native_modules.values() {
        for import in &hir_module.imports {
            let spec = &import.source;
            // Skip relative/absolute — only bare specs need an alias.
            if spec.starts_with("./")
                || spec.starts_with("../")
                || spec.starts_with('/')
                || spec.starts_with("file://")
                || spec.starts_with("node:")
            {
                continue;
            }
            if let Some(ref resolved) = import.resolved_path {
                if ctx.js_modules.contains_key(resolved) {
                    aliases.insert(spec.clone(), resolved.clone());
                }
            }
        }
    }
    // JS-bundled modules sometimes have a `package.json` "name" we could
    // also register, but the import-edge alias map already covers the
    // shapes the V8 loader sees (TS-side bare imports). For relative
    // imports between JS files the path-keyed map handles it directly.

    for (idx, (specifier, path)) in aliases.iter().enumerate() {
        let spec_lit = c_string_literal(specifier);
        let path_lit = c_string_literal(path);
        c.push_str(&format!(
            "static const char PERRY_ALIAS_SPEC_{idx}[] = {spec_lit};\n"
        ));
        c.push_str(&format!(
            "static const size_t PERRY_ALIAS_SPEC_LEN_{idx} = {};\n",
            specifier.len()
        ));
        c.push_str(&format!(
            "static const char PERRY_ALIAS_PATH_{idx}[] = {path_lit};\n"
        ));
        c.push_str(&format!(
            "static const size_t PERRY_ALIAS_PATH_LEN_{idx} = {};\n",
            path.len()
        ));
    }

    // Constructor: register every entry before the runtime spins up.
    // Priority 101 is the lowest user-defined value (0-100 are reserved
    // for the implementation); this runs before any normal C++ static
    // initializer or user constructor.
    c.push_str("__attribute__((constructor(101)))\n");
    c.push_str("static void perry_register_embedded_js(void) {\n");
    for idx in 0..ctx.js_modules.len() {
        c.push_str(&format!(
            "    js_register_embedded_module(PERRY_EMB_PATH_{idx}, PERRY_EMB_PATH_LEN_{idx}, PERRY_EMB_SRC_{idx}, PERRY_EMB_SRC_LEN_{idx});\n"
        ));
    }
    for idx in 0..aliases.len() {
        c.push_str(&format!(
            "    js_register_embedded_alias(PERRY_ALIAS_SPEC_{idx}, PERRY_ALIAS_SPEC_LEN_{idx}, PERRY_ALIAS_PATH_{idx}, PERRY_ALIAS_PATH_LEN_{idx});\n"
        ));
    }
    c.push_str("}\n");

    fs::write(&c_path, &c)?;

    let status = Command::new("cc")
        .arg("-c")
        .arg(&c_path)
        .arg("-O0")
        .arg("-o")
        .arg(&obj_path)
        .status()
        .map_err(|e| anyhow!("Failed to invoke cc for embedded JS bundle: {}", e))?;
    if !status.success() {
        return Err(anyhow!(
            "cc failed to compile embedded JS bundle ({})",
            c_path.display()
        ));
    }
    Ok(obj_path)
}

/// Render a Rust string as a C string literal, escaping all non-ASCII
/// and special bytes byte-by-byte. We deliberately use octal escapes for
/// every byte ≥ 0x80 (and quotes/backslash/control chars) instead of
/// embedding raw UTF-8 — keeps the resulting source ASCII-clean and
/// avoids surprising the host C compiler with a multi-byte character set
/// it doesn't recognize. Length is reported as the byte length to match
/// the `size_t` parameter on the runtime side.
fn c_string_literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for &b in s.as_bytes() {
        match b {
            b'"' => out.push_str("\\\""),
            b'\\' => out.push_str("\\\\"),
            b'\n' => out.push_str("\\n"),
            b'\r' => out.push_str("\\r"),
            b'\t' => out.push_str("\\t"),
            // `?` only needs escaping inside trigraph sequences; modern
            // toolchains either disable trigraphs (clang default) or accept
            // the literal. Escape just to be safe — embedded `??=`, `??/`
            // etc. inside JS source could otherwise change meaning under
            // `-trigraphs`.
            b'?' => out.push_str("\\?"),
            0x20..=0x7E => out.push(b as char),
            _ => {
                use std::fmt::Write;
                let _ = write!(out, "\\{:03o}", b);
            }
        }
    }
    out.push('"');
    out
}



/// Build a WidgetKit .appex extension by invoking `xcrun swiftc` on the
/// generated SwiftUI sources. Produces `<output_dir>/<extension_name>.appex/`
/// containing the compiled mach-O binary plus a resolved Info.plist (Xcode
/// build variables like `$(EXECUTABLE_NAME)` substituted to concrete values
/// since there's no Xcode driver doing the substitution).
///
/// Returns the absolute path of the produced `.appex` directory.
fn build_widget_appex(
    output_dir: &Path,
    swift_files: &[(String, String)],
    info_plist: &str,
    sdk: &str,
    target_triple: &str,
    frameworks: &[&str],
    extension_name: &str,
    format: OutputFormat,
) -> Result<PathBuf> {
    // Resolve SDK path up-front so a missing Xcode/CLT toolchain fails with
    // a clearer message than swiftc's own diagnostic.
    let sdk_path_output = Command::new("xcrun")
        .args(["--sdk", sdk, "--show-sdk-path"])
        .output()
        .map_err(|e| {
            anyhow!(
                "Failed to invoke `xcrun --sdk {} --show-sdk-path`: {}. \
                 Install Xcode or the Command Line Tools (`xcode-select --install`), \
                 or pass --skip-swift-build to emit sources only.",
                sdk,
                e
            )
        })?;
    if !sdk_path_output.status.success() {
        return Err(anyhow!(
            "`xcrun --sdk {} --show-sdk-path` failed: {}",
            sdk,
            String::from_utf8_lossy(&sdk_path_output.stderr)
        ));
    }
    let sdk_path = String::from_utf8(sdk_path_output.stdout)?
        .trim()
        .to_string();

    let appex_dir = output_dir.join(format!("{}.appex", extension_name));
    fs::create_dir_all(&appex_dir)?;

    let resolved_plist = info_plist
        .replace("$(EXECUTABLE_NAME)", extension_name)
        .replace("$(PRODUCT_NAME)", extension_name)
        .replace("$(PRODUCT_BUNDLE_PACKAGE_TYPE)", "XPC!");
    fs::write(appex_dir.join("Info.plist"), &resolved_plist)?;

    let binary_path = appex_dir.join(extension_name);

    let mut cmd = Command::new("xcrun");
    cmd.args(["--sdk", sdk, "swiftc"])
        .args(["-target", target_triple])
        .args(["-sdk", &sdk_path])
        .arg("-emit-executable")
        .arg("-parse-as-library")
        .arg("-O");
    for (filename, _) in swift_files {
        cmd.arg(output_dir.join(filename));
    }
    for fw in frameworks {
        cmd.args(["-framework", fw]);
    }
    cmd.arg("-o").arg(&binary_path);

    if matches!(format, OutputFormat::Text) {
        println!("Invoking swiftc → {}", binary_path.display());
    }

    let status = cmd.status().map_err(|e| {
        anyhow!(
            "Failed to invoke swiftc: {}. Install Xcode or the Command Line Tools \
             (`xcode-select --install`), or pass --skip-swift-build to emit sources only.",
            e
        )
    })?;
    if !status.success() {
        return Err(anyhow!(
            "swiftc failed (exit {}). The generated SwiftUI source is at {}/ — \
             rerun with --skip-swift-build to inspect or hand off to xcodebuild.",
            status.code().unwrap_or(-1),
            output_dir.display()
        ));
    }

    Ok(appex_dir)
}


/// Find the PerryWatchApp.swift runtime file.
pub(super) fn find_watchos_swift_runtime() -> Option<PathBuf> {
    // 1. Check next to the perry binary
    if let Ok(exe) = std::env::current_exe() {
        if let Some(dir) = exe.parent() {
            let candidate = dir.join("swift").join("PerryWatchApp.swift");
            if candidate.exists() {
                return Some(candidate);
            }
            // Also check ../lib/perry/swift/
            if let Some(prefix) = dir.parent() {
                let candidate = prefix
                    .join("lib")
                    .join("perry")
                    .join("swift")
                    .join("PerryWatchApp.swift");
                if candidate.exists() {
                    return Some(candidate);
                }
            }
        }
    }

    // 2. Check the workspace checkout (PERRY_WORKSPACE_ROOT / exe / cwd
    // walk) so npm/homebrew installs pointed at a source tree resolve the
    // Swift shell the same way they resolve runtime/stdlib.
    if let Some(root) = super::find_perry_workspace_root() {
        let candidate = root.join("crates/perry-ui-watchos/swift/PerryWatchApp.swift");
        if candidate.exists() {
            return Some(candidate);
        }
    }

    // 3. Check in the source tree (development builds)
    let source_candidate = PathBuf::from("crates/perry-ui-watchos/swift/PerryWatchApp.swift");
    if source_candidate.exists() {
        return Some(source_candidate);
    }

    None
}

